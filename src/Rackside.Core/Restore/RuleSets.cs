namespace Rackside.Core.Restore;

/// <summary>A conversion rule: regex P, reason M and, for Replace, the replacement R.</summary>
public sealed record ConversionRule(string P, string M, string R = "");

/// <summary>
/// RemoveBlock: regex on the top-level line, removes the line and its sublines. RemoveChild: regex on a
/// subline. Replace: regex -> replacement, on top-level lines and sublines.
/// </summary>
public sealed record RuleSet(string Name, IReadOnlyList<ConversionRule> RemoveBlock, IReadOnlyList<ConversionRule> RemoveChild, IReadOnlyList<ConversionRule> Replace);

