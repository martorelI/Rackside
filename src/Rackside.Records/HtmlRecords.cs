    private static readonly Lazy<string> LogoBase64 = new(() =>
    {
        using var s = typeof(HtmlRecords).Assembly.GetManifestResourceStream("Rackside.Records.logo.png")!;
        using var ms = new MemoryStream();
        s.CopyTo(ms);
        return Convert.ToBase64String(ms.ToArray());
    });

    /// <summary>The embedded logo in base64 (the tests replace it to compare with the snapshots).</summary>
    public static string Logo => LogoBase64.Value;

    public static string H(object? x) => x is null ? string.Empty : WebUtility.HtmlEncode(Convert.ToString(x, CultureInfo.InvariantCulture)) ?? string.Empty;

    /// <summary>Writes the page (UTF-8 without BOM).</summary>
    public static void Write(string path, string html) => File.WriteAllText(path, html, new UTF8Encoding(false));

    /// <summary>SHA-256 of a file, or empty.</summary>
    public static string Sha256(string? path) =>
        string.IsNullOrEmpty(path) || !File.Exists(path) ? string.Empty : Convert.ToHexString(System.Security.Cryptography.SHA256.HashData(File.ReadAllBytes(path)));

    private sealed class Page(Translator t)
    {
        private readonly StringBuilder sb = new();
        private int section;

        public void L(string line) => sb.Append(line).Append("\r\n");

        public string Sec(string title) => Ci.F("<h2>{0}. {1}</h2>", ++section, t.T(title));

        public string Row(string k, object? v) => Ci.F("<tr><th>{0}</th><td>{1}</td></tr>", H(t.T(k)), H(v));

        public override string ToString() => sb.ToString();
    }

    /// <summary>Common header with the logo.</summary>
    public string Header(string title, string date, string device) =>
        Ci.F(t.T("<div class=\"noprint print-bar\"><button type=\"button\" onclick=\"window.print()\">Print / Save as PDF</button></div><div class=\"head\"><img src=\"data:image/png;base64,{0}\" alt=\"\"><div><h1>{1}</h1><div class=\"sub\">Generated by {2} {3} on {4} from {5}</div></div></div>"),
            Logo, title, H(AppInfo.Name), H(AppInfo.Version), H(date), H(device));

    private static string Color(string result) => result switch
    {
        "SUCCESSFUL" => "#1e7b34",
        "SUCCESSFUL WITH NOTES" => "#b36b00",
        "FAILED" => "#b00020",
        _ => "#555555",
    };

    private static string Css3(string result) => result == "FAIL" ? "bad" : result != "OK" ? "warn" : "ok";

    private void Start(Page p, string title, string header, RecordBase d)
    {
        p.L(t.T("<!DOCTYPE html><html lang=\"en\"><head><meta charset=\"utf-8\">"));
        p.L(title);
        p.L(Ci.F("<style>{0}</style></head><body>", Css));
        p.L(Header(t.T(header), d.EndText, d.DeviceWork));
        p.L(Ci.F(t.T("<div class=\"res\" style=\"background:{0}\">RESULT: {1}</div>"), Color(d.Result), H(t.T(d.Result))));
    }

    private void Checks(Page p, IEnumerable<PushCheck> items)
    {
        foreach (var v in items)
        {
            p.L(Ci.F("<tr><td>{0}</td><td class=\"{1}\">{2}</td><td>{3}</td></tr>", H(v.Check), Css3(v.Result), H(t.T(v.Result)), H(v.Detail)));
        }
    }

    private void Signatures(Page p) =>
        p.L(t.T("<div class=\"signatures\"><div class=\"signature\">Performed by</div><div class=\"signature\">Validated by</div><div class=\"signature\">Approved by</div></div>"));

    private void ManualChecks(Page p, IEnumerable<string> items)
    {
        p.L(p.Sec(t.T("Post-change validation (fill in by hand)")) + t.T("<table class=\"lista chk\"><tr><th></th><th>Check</th><th>Notes</th></tr>"));
        foreach (var x in items)
        {
            p.L(Ci.F("<tr><td>&#9744;</td><td>{0}</td><td></td></tr>", H(x)));
        }
        p.L("</table>");
    }

    private void EventDetails(Page p, RecordBase d, string ticketLabel)
    {
        p.L(p.Sec(t.T("Event details")) + "<table>");
        p.L(p.Row(t.T(ticketLabel), d.Ticket));
        p.L(p.Row(t.T("Responsible"), d.Responsible));
        p.L(p.Row(t.T("Windows user / computer"), Ci.F("{0} / {1}", d.UserWindows, d.DeviceWork)));
        p.L(p.Row(t.T("Start"), d.StartText));
        p.L(p.Row(t.T("End"), d.EndText));
        p.L(p.Row(t.T("Duration"), d.Duration));
    }

    /// <summary>DRP execution record.</summary>
    public string Drp(DrpRecordData d)
    {
        ArgumentNullException.ThrowIfNull(d);
        var p = new Page(t);
        Start(p, Ci.F(t.T("<title>DRP record - {0} - {1}</title>"), H(d.HostnameFinal), H(d.StartText)), "DRP execution record &mdash; Network switch replacement", d);
        if (d.ErrorFatal.Length > 0)
        {
            p.L(Ci.F(t.T("<p class=\"bad\">Reason: {0}</p>"), H(d.ErrorFatal)));
        }
        EventDetails(p, d, "Ticket / incident");
        p.L(p.Row(t.T("Notes"), d.Remarks));
        p.L("</table>");

        p.L(p.Sec(t.T("Devices")) + t.T("<table class=\"lista\"><tr><th></th><th>Failed device (source)</th><th>Replacement device (target)</th></tr>"));
        p.L(Ci.F(t.T("<tr><th>Hostname</th><td>{0}</td><td>{1}</td></tr>"), H(d.FailedHost), H(d.HostnameFinal)));
        p.L(Ci.F(t.T("<tr><th>Model</th><td>{0}</td><td>{1}</td></tr>"), H(d.FailedModel), H(d.ReplacementModel)));
        p.L(Ci.F(t.T("<tr><th>Serial number</th><td>{0}</td><td>{1}</td></tr>"), H(d.FailedSerial), H(d.ReplacementSerial)));
        p.L(Ci.F(t.T("<tr><th>Operating system</th><td>{0}</td><td>{1}</td></tr>"), H(d.FailedOS), H(d.ReplacementOS)));
        p.L(Ci.F(t.T("<tr><th>Management IP</th><td colspan=\"2\">{0}</td></tr>"), H(d.IPManagement)));
        p.L("</table>");

        p.L(p.Sec(t.T("Backup used and configuration applied")) + "<table>");
        p.L(p.Row(t.T("Backup file"), d.BackupPath));
        p.L(p.Row(t.T("Backup date (modified)"), d.BackupDate));
        p.L(p.Row(t.T("Size"), d.BackupSize));
        p.L(p.Row(t.T("Backup SHA-256"), d.BackupHash));
        p.L(p.Row(t.T("Mode"), t.T(d.Mode)));
        p.L(p.Row(t.T("Lines sent"), d.Lines));
        p.L(p.Row(t.T("SHA-256 of the applied configuration"), d.ConfigHash));
        p.L(p.Row(t.T("Evidence folder"), d.Folder));
        p.L("</table>");

        p.L(p.Sec(t.T("Automatic verification")) + t.T("<table class=\"lista\"><tr><th>Check</th><th>Result</th><th>Detail</th></tr>"));
        Checks(p, d.Verification);
        p.L("</table>");

        p.L(p.Sec(Ci.F(t.T("Errors returned by the switch ({0})"), d.Errors.Count)));
        if (d.Errors.Count == 0)
        {
            p.L(t.T("<p class=\"ok\">None.</p>"));
        }
        else
        {
            p.L(t.T("<table class=\"lista\"><tr><th>Line</th><th>Switch response</th></tr>"));
            foreach (var e in d.Errors)
            {
                p.L(Ci.F("<tr><td><code>{0}</code></td><td>{1}</td></tr>", H(e.Line), H(e.Answer)));
            }
            p.L("</table>");
        }
        if (d.Warnings.Count > 0)
        {
            p.L(p.Sec(Ci.F(t.T("Switch warnings ({0})"), d.Warnings.Count)) + t.T("<table class=\"lista\"><tr><th>Line</th><th>Message</th></tr>"));
            foreach (var a in d.Warnings)
            {
                p.L(Ci.F("<tr><td><code>{0}</code></td><td>{1}</td></tr>", H(a.Line), H(a.Answer)));
            }
            p.L("</table>");
        }

        p.L(p.Sec(t.T("Changes from the backup")));
        if (d.Changes.Count == 0)
        {
            p.L(t.T("<p>The backup was applied as is.</p>"));
        }
        else
        {
            p.L(t.T("<table class=\"lista\"><tr><th>Type</th><th>Line</th><th>Reason</th></tr>"));
            foreach (var c in d.Changes)
            {
                p.L(Ci.F("<tr><td>{0}</td><td><code>{1}</code></td><td>{2}</td></tr>", H(t.T(c.Type)), H(c.Line), H(c.Reason)));
            }
            p.L("</table>");
        }
        if (d.Mapping.Count > 0)
        {
            p.L(p.Sec(t.T("Interface mapping")) + t.T("<table class=\"lista\"><tr><th>Source</th><th>Target</th><th>Role</th></tr>"));
            foreach (var m in d.Mapping)
            {
                p.L(Ci.F("<tr><td>{0}</td><td>{1}</td><td>{2}</td></tr>", H(m.Source), H(m.Target), H(t.T(m.Role))));
            }
            p.L("</table>");
        }
        ManualChecks(p,
        [
            t.T("SSH access to the management IP with the administrator user"), t.T("Uplink(s) up and trunking (show interfaces trunk)"), t.T("VLANs present (show vlan brief)"),
            t.T("Expected neighbors (show cdp neighbors / show lldp neighbors)"), t.T("End devices and phones have connectivity"),
            t.T("Monitoring / SNMP / syslog receiving from the new device"), t.T("New backup taken from the replacement switch"), t.T("Inventory and labels updated with the new serial number"),
        ]);
        Signatures(p);
        p.L(t.T("<h2>Appendix A. Applied configuration</h2>"));
        p.L(Ci.F("<pre>{0}</pre>", H(d.ConfigText)));
        p.L("</body></html>");
        return p.ToString();
    }

    private void ActionsAndVerification(Page p, IReadOnlyList<PushCheck> actions, IReadOnlyList<PushCheck> verification)
    {
        foreach (var (title, list) in new[] { (t.T("Actions performed"), actions), ("Verification", verification) })
        {
            p.L(p.Sec(title) + t.T("<table class=\"lista\"><tr><th>Check</th><th>Result</th><th>Detail</th></tr>"));
            Checks(p, list);
            if (list.Count == 0)
            {
                p.L(t.T("<tr><td colspan=\"3\">No entries (the operation stopped earlier).</td></tr>"));
            }
            p.L("</table>");
        }
    }

    /// <summary>Factory reset record.</summary>
    public string Reset(ResetRecordData d)
    {
        ArgumentNullException.ThrowIfNull(d);
        var p = new Page(t);
        Start(p, Ci.F(t.T("<title>Factory reset - {0} - {1}</title>"), H(d.Hostname), H(d.StartText)), "Factory reset record &mdash; Switch", d);
        if (d.ErrorFatal.Length > 0)
        {
            p.L(Ci.F("<p class=\"bad\">{0}</p>", H(d.ErrorFatal)));
        }
        EventDetails(p, d, "Ticket / reference");
        p.L(p.Row(t.T("Reason"), d.Reason));
        p.L("</table>");
        p.L(p.Sec(t.T("Device")) + "<table>");
        p.L(p.Row(t.T("Previous hostname"), d.Hostname));
        p.L(p.Row(t.T("Model"), d.Model));
        p.L(p.Row(t.T("Serial number"), d.Serial));
        p.L(p.Row(t.T("Operating system"), Ci.F("{0} {1}", d.OS, d.Version)));
        p.L(p.Row(t.T("Stack members"), d.Members));
        p.L(p.Row(t.T("Image kept"), string.Join(", ", d.Protected.Select(x => d.Filesystem + ":" + x))));
        p.L("</table>");
        p.L(p.Sec(t.T("Backup before erasing")) + "<table>");
        p.L(p.Row(t.T("File"), d.BackupPath));
        p.L(p.Row(t.T("SHA-256"), d.BackupHash));
        p.L(p.Row(t.T("Evidence folder"), d.Folder));
        p.L("</table>");
        ActionsAndVerification(p, d.Actions, d.Verification);
        Signatures(p);
        p.L("</body></html>");
        return p.ToString();
    }

    /// <summary>IOS update record.</summary>
    public string Upgrade(UpgradeRecordData d)
    {
        ArgumentNullException.ThrowIfNull(d);
        var p = new Page(t);
        var method = d.Method switch { "USB" => t.T("USB connected to the switch"), "SERIAL" => t.T("Xmodem over the console"), "SSH" => t.T("SCP over SSH"), _ => string.Empty };
        Start(p, Ci.F(t.T("<title>IOS update - {0} - {1}</title>"), H(d.Hostname), H(d.StartText)), "IOS update record &mdash; Switch", d);
        if (d.ErrorFatal.Length > 0)
        {
            p.L(Ci.F("<p class=\"bad\">{0}</p>", H(d.ErrorFatal)));
        }
        EventDetails(p, d, "Ticket / change");
        p.L("</table>");
        p.L(p.Sec(t.T("Device and version")) + "<table>");
        p.L(p.Row(t.T("Hostname"), d.Hostname));
        p.L(p.Row(t.T("Model"), d.Model));
        p.L(p.Row(t.T("Serial number"), d.Serial));
        p.L(p.Row(t.T("Stack members"), d.Members));
        p.L(p.Row(t.T("Previous version"), Ci.F("{0} {1}", d.OS, d.Version)));
        p.L(p.Row(t.T("Expected version"), d.VersionExpected));
        p.L(p.Row(t.T("Version after"), d.VersionAfter));
        p.L("</table>");
        p.L(p.Sec(t.T("Image")) + "<table>");
        p.L(p.Row(t.T("File"), d.ImageName));
        p.L(p.Row(t.T("Size"), string.Format(CultureInfo.CurrentCulture, "{0:N0} bytes", d.Bytes)));
        p.L(p.Row(t.T("Load method"), method));
        p.L(p.Row(t.T("Control connection"), d.Connection == "SSH" ? "SSH " + d.IP : t.T("Console ") + d.PortCom));
        if (d.Fingerprint.Length > 0)
        {
            p.L(p.Row(t.T("SSH fingerprint accepted"), d.Fingerprint));
        }
        p.L(p.Row(t.T("MD5 published by Cisco"), d.Md5Expected.Length > 0 ? d.Md5Expected : t.T("(not entered)")));
        p.L(p.Row(t.T("Local file MD5"), d.Md5Local.Length > 0 ? d.Md5Local : t.T("(not applicable: loaded from USB)")));
        p.L(p.Row(t.T("MD5 computed by the switch"), d.Md5Switch));
        p.L(p.Row(t.T("Evidence folder"), d.Folder));
        p.L("</table>");
        ActionsAndVerification(p, d.Actions, d.Verification);
        ManualChecks(p,
        [
            t.T("SSH and console access"), t.T("Uplinks and trunks up"), t.T("VLANs and STP unchanged (show vlan brief, show spanning-tree summary)"), t.T("Phones / PoE working"),
            t.T("Monitoring receiving from the device"), t.T("New configuration backup"),
        ]);
        Signatures(p);
        p.L("</body></html>");
        return p.ToString();
    }

    /// <summary>Push record. Details go through the masker again.</summary>
    public string Push(PushRecordData d, SecretMasker masker)
    {
        ArgumentNullException.ThrowIfNull(d);
        ArgumentNullException.ThrowIfNull(masker);
        var p = new Page(t);
        static string Cls(string res) => res is "OK" or "SUCCESSFUL" ? "ok" : res is "FAIL" or "FAILED" or "WITH FAILURES" ? "bad" : "warn";
        p.L(t.T("<!DOCTYPE html><html lang=\"en\"><head><meta charset=\"utf-8\">"));
        p.L(Ci.F(t.T("<title>Configuration push - {0}</title>"), H(d.StartText)));
        p.L(Ci.F("<style>{0}</style></head><body>", Css));
        p.L(Header(t.T("Configuration push record"), d.EndText, d.DeviceWork));
        var worst = d.Results.Any(r => r.Result is PushOutcome.Failed or PushOutcome.WithFailures) ? "WITH FAILURES"
            : d.Results.Any(r => r.Result != PushOutcome.Successful) ? "WITH NOTES" : "SUCCESSFUL";
        var color = worst switch { "SUCCESSFUL" => "#1e7b34", "WITH NOTES" => "#b36b00", _ => "#b00020" };
        p.L(Ci.F(t.T("<div class=\"res\" style=\"background:{0}\">RESULT: {1}</div> <span>{2}</span>"), color, H(t.T(worst)), H(d.Summary)));

        p.L(p.Sec(t.T("Event details")) + "<table>");
        p.L(p.Row(t.T("Ticket / change"), d.Ticket));
        p.L(p.Row(t.T("Responsible"), d.Responsible));
        p.L(p.Row(t.T("Windows user / computer"), Ci.F("{0} / {1}", d.UserWindows, d.DeviceWork)));
        p.L(p.Row(t.T("User on the switches"), d.UserSwitch));
        p.L(p.Row(t.T("Connection"), d.Connection));
        p.L(p.Row(t.T("Start"), d.StartText));
        p.L(p.Row(t.T("End"), d.EndText));
        p.L(p.Row(t.T("Duration"), d.Duration));
        p.L(p.Row(t.T("Groups pushed"), d.Groups));
        p.L(p.Row(t.T("Save to startup-config"), d.Save));
        p.L(p.Row(t.T("Evidence folder"), d.Folder));
        p.L("</table>");

        p.L(p.Sec(t.T("Summary by switch")) + t.T("<table class=\"lista\"><tr><th>Switch</th><th>IP</th><th>Hostname</th><th>Model / version</th><th>Result</th><th>Saved</th><th>Detail</th></tr>"));
        foreach (var r in d.Results)
        {
            p.L(Ci.F("<tr><td>{0}</td><td>{1}</td><td>{2}</td><td>{3}</td><td class=\"{4}\">{5}</td><td>{6}</td><td>{7}</td></tr>", H(r.Name), H(r.IP), H(r.Hostname),
                H(Ci.F("{0} {1} {2}", r.Model, r.Platform, r.Version).Trim()), Cls(r.Result.Code()), H(t.T(r.Result.Code())), H(r.Saved), H(masker.Protect(r.Detail))));
        }
        p.L("</table>");
        p.L(p.Sec(t.T("Pushed parameters (preview)")) + Ci.F("<pre>{0}</pre>", H(d.View)));

        foreach (var r in d.Results)
        {
            p.L(p.Sec(Ci.F(t.T("Detail: {0} {1}"), r.Name, r.IP.Length > 0 ? "(" + r.IP + ")" : string.Empty)) + "<table>");
            p.L(p.Row(t.T("Result"), Ci.F("{0} - {1}", t.T(r.Result.Code()), masker.Protect(r.Detail))));
            p.L(p.Row(t.T("Hostname / serial"), Ci.F("{0} / {1}", r.Hostname, r.Serial)));
            if (r.Fingerprint.Length > 0)
            {
                p.L(p.Row(t.T("SSH fingerprint accepted"), r.Fingerprint));
            }
            p.L(p.Row(t.T("Saved"), r.Saved));
            p.L(p.Row(t.T("Time"), Ci.F("{0} - {1}", r.Start.ToString("HH:mm:ss", CultureInfo.InvariantCulture), r.End?.ToString("HH:mm:ss", CultureInfo.InvariantCulture) ?? string.Empty)));
            if (r.Folder.Length > 0 && Directory.Exists(r.Folder))
            {
                var files = string.Join(", ", Directory.GetFiles(r.Folder).Select(Path.GetFileName).Order(StringComparer.OrdinalIgnoreCase));
                p.L(p.Row(t.T("Evidence"), Ci.F("{0} ({1})", r.Folder, files)));
            }
            p.L("</table>");
            if (r.Verification.Count > 0)
            {
                p.L(t.T("<table class=\"lista\"><tr><th>Line / check</th><th>Result</th><th>Detail</th></tr>"));
                foreach (var v in r.Verification)
                {
                    p.L(Ci.F("<tr><td>{0}</td><td class=\"{1}\">{2}</td><td>{3}</td></tr>", H(v.Check), Cls(v.Result), H(t.T(v.Result)), H(v.Detail)));
                }
                p.L("</table>");
            }
            if (r.Warnings.Count > 0)
            {
                p.L(t.T("<p><b>Switch messages</b></p><table class=\"lista\"><tr><th>Line</th><th>Message</th></tr>"));
                foreach (var (line, answer) in r.Warnings)
                {
                    p.L(Ci.F("<tr><td>{0}</td><td>{1}</td></tr>", H(line), H(answer)));
                }
                p.L("</table>");
            }
        }
        ManualChecks(p,
        [
            t.T("SSH access to the pushed switches (new session)"), t.T("Monitoring / SNMP receiving from the switches"), t.T("Correct time (show clock) and NTP synchronized (show ntp status)"),
            t.T("Syslog receiving events"), t.T("LLDP / CDP neighbors and IP phones working"), t.T("New configuration backup"),
        ]);
        Signatures(p);
        p.L("</body></html>");
        return p.ToString();
    }

    /// <summary>Fallback record: if the full one fails, there is always a printable HTML with the essentials.</summary>
    public string Minimal(string title, IEnumerable<(string Key, string Value)> data, string failure, string? date = null, string? device = null)
    {
        ArgumentNullException.ThrowIfNull(data);
        var p = new Page(t);
        p.L(t.T("<!DOCTYPE html><html lang=\"en\"><head><meta charset=\"utf-8\">"));
        p.L(Ci.F("<title>{0}</title><style>{1}</style></head><body>", H(title), Css));
        p.L(Header(H(title), date ?? DateTime.Now.ToString("yyyy-MM-dd HH:mm:ss", CultureInfo.InvariantCulture), device ?? Environment.MachineName));
        p.L(Ci.F(t.T("<p class=\"bad\">Reduced record: the full record could not be generated ({0}). Details are in log.txt, report.txt and console_session.txt in the same folder.</p>"), H(failure)));
        p.L("<table>");
        foreach (var (k, v) in data)
        {
            p.L(Ci.F("<tr><th>{0}</th><td>{1}</td></tr>", H(t.T(k)), H(v)));
        }
        p.L("</table>");
        Signatures(p);
        p.L("</body></html>");
        return p.ToString();
    }

    /// <summary>Printable switch list with what the last query documented.</summary>
    public string InventoryDocument(IReadOnlyList<InventoryRow> rows, string? date = null, string? device = null)
    {
        ArgumentNullException.ThrowIfNull(rows);
        var p = new Page(t);
        string[] cols = ["Name", "IP", "Hostname", "Model", "Serial", "Platform", "Version", "LLDP", "CDP", "VTP", "STP", "Domain", "SNMP", "NTP", "Syslog", "Banner", "SSH", "Status", "Date"];
        p.L(t.T("<!DOCTYPE html><html lang=\"en\"><head><meta charset=\"utf-8\"><title>Switch inventory</title>"));
        p.L(Ci.F(t.T("<style>{0} body{{max-width:none}} table.inv td,table.inv th{{font-size:11px}} @page{{size:landscape}}</style></head><body>"), Css));
        p.L(Header(t.T("Switch inventory"), date ?? DateTime.Now.ToString("yyyy-MM-dd HH:mm:ss", CultureInfo.InvariantCulture), device ?? Environment.MachineName));
        p.L(Ci.F(t.T("<p>{0} switch(es). Data from the last query or push of each one (Date column). SNMP communities and passwords are not included.</p>"), rows.Count));
        p.L(Ci.F("<table class=\"lista inv\"><tr>{0}</tr>", string.Concat(cols.Select(c => "<th>" + H(c) + "</th>"))));
        foreach (var f in rows)
        {
            p.L(Ci.F("<tr>{0}</tr>", string.Concat(cols.Select(c => "<td>" + H(f[c]) + "</td>"))));
        }
        p.L("</table></body></html>");
        return p.ToString();
    }
