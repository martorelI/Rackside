/// <summary>
/// The printable HTML records (restore, factory reset, IOS update, push, reduced record and switch list),
/// with the embedded logo.
/// </summary>
public sealed class HtmlRecords(Translator t)
{
    /// <summary>CSS shared by every record.</summary>
    public const string Css = """
body{font-family:"Segoe UI",Arial,sans-serif;font-size:13px;color:#222;max-width:1000px;margin:24px auto;padding:0 16px}
.head{display:flex;align-items:center;gap:14px;border-bottom:3px solid #1E6BB8;padding-bottom:10px;margin-bottom:14px}
